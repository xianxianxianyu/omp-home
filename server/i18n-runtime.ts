import type { RequestAnswerKind } from "../shared/transcript.ts";
import { defineMessages, render, type Message } from "./i18n.ts";

const answers: Record<RequestAnswerKind, Message> = {
	cancelled: { en: "Cancelled", zh: "已取消" },
	yes: { en: "Yes", zh: "是" },
	no: { en: "No", zh: "否" },
	withdrawn: { en: "Withdrawn", zh: "已撤回" },
	session_ended: { en: "Session ended", zh: "会话已结束" },
};

const en = {
	ompUnresolved: () => "omp has not been resolved yet",
	ompNotFound: () => "omp was not found",
	ompNotExecutable: (file: string) => `${file} (the configured omp path) is not an executable file`,
	ompMissing: (dirs: string) => `omp was not found on PATH or in ${dirs}; install omp (https://omp.sh) or set its path in Settings`,
	ompNoVersion: (file: string) => `${file} --version printed no version`,
	ompCheckFailed: (version: string | null, file: string, reason: string | Message) => `omp ${version ?? "(unknown version)"} at ${file} failed the omp-home compatibility check: ${render(reason)}`,
	ompKeepingManaged: (reason: Message, version: string) => `${reason.en}. Still using omp ${version}.`,
	ompUsingUnchecked: (reason: Message) => `${reason.en}. Using it anyway; sessions may not work.`,
	checkTimeout: (seconds: number) => `no answer within ${seconds}s`,
	checkExited: (detail: string) => `omp exited: ${detail}`,
	bridgeDisconnected: (detail: string | Message) => `the omp-home bridge extension did not connect (${render(detail)})`,
	missingToolList: () => "get_state has no tool list",
	missingBridgeTools: (tools: string) => `the bridge tools ${tools} are missing from get_state`,
	rpcExited: (code: number | null, signal: string | null, detail: string) => `omp exited (${signal ?? `code ${code}`})${detail ? `: ${detail}` : ""}`,
	rpcCommandFailed: (command: string) => `${command} failed`,
	rpcTimeout: (command: string, seconds: number) => `omp did not answer ${command} within ${seconds}s`,
	rpcNotRunning: () => "omp is not running",
	rpcTooLarge: () => "message exceeds the 64 MiB limit of one omp command",
	promptFailed: (detail: string | null) => `prompt failed: ${detail ?? "unknown error"}`,
	extensionFailed: (event: string, detail: string) => `extension ${event} failed: ${detail}`,
	noRequest: (request: string, session: string) => `no request ${request} in ${session}`,
	requestAnswered: (request: string, answer: string | Message) => `request ${request} was already answered (${render(answer)})`,
	historyCursor: (cursor: string) => `unknown history cursor ${cursor}; reload the session`,
	answer: (kind: RequestAnswerKind) => answers[kind].en,
	truncated: (count: number) => `…[${count} earlier ${count === 1 ? "character" : "characters"} not shown]`,
};

