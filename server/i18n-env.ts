import type { FieldError } from "../shared/api.ts";
import { localizeFieldErrors } from "./errors.ts";
import { defineMessages, render, type Message } from "./i18n.ts";

const en = {
	worktreeMissing: (id: string) => `worktree ${id} is not present on disk`,
	invalidRecipe: (file: string, errors: readonly FieldError[]) => `recipe ${file} is invalid: ${errors.map(e => `${e.path || "(root)"}: ${e.message}`).join("; ")}`,
	setupFailed: (code: number, command: string, output: string | Message) => `setup command failed (exit ${code}): ${command}\n${render(output)}`,
	environmentFailed: (detail: string | Message) => `environment failed: ${render(detail)}`,
	withLog: (detail: string | Message, log: string) => `${render(detail)}\nLog: ${log}`,
	databaseLeased: (name: string, holderKind: "worktree" | "service" | "session", holderId: string) => `database ${name} is already leased by ${holderKind} ${holderId}`,
	databaseCloneFailed: (code: number, output: string | Message) => `database clone failed (exit ${code}): ${render(output)}`,
	startFailed: (code: number, output: string | Message) => `start failed (exit ${code}): ${render(output)}`,
	serviceStartFailed: (name: string, code: number, log: string) => `service ${name}: start failed (exit ${code}). Log: ${log}`,
	checkTimeout: (seconds: number) => `check still failing after ${seconds}s`,
	serviceCheckTimeout: (name: string, seconds: number, log: string, tail: string) => `service ${name}: check still failing after ${seconds}s. Log: ${log}\n${tail}`,
	serviceMissing: (id: string, workspace: string) => `service ${id} is not in the ${workspace} recipe`,
	checkFailed: (code: number) => `check failed (exit ${code})`,
	stopFailed: (code: number, output: string | Message) => `stop failed (exit ${code}): ${render(output).slice(-500)}`,
	noStopCommand: (id: string) => `service ${id} has no stop command in the recipe`,
	teardownFailed: (code: number, command: string, log: string) => `teardown command failed (exit ${code}): ${command}. Log: ${log}`,
	databaseDropFailed: (code: number, log: string) => `database drop failed (exit ${code}). Log: ${log}`,
	portsExhausted: (lo: number, hi: number) => `no free port left in ${lo}-${hi}; widen settings.portRange or clean up finished tasks`,
	noValidRecipe: (workspace: string) => `workspace ${workspace} has no valid recipe`,
	noAccountPool: (pool: string, known: readonly string[]) => `no account pool "${pool}"${known.length ? `; pools: ${known.join(", ")}` : "; the recipe defines none"}`,
	accountsLeased: (count: number, pool: string) => `all ${count} accounts in "${pool}" are leased; try again after a worker's turn ends`,
	accountEnvMissing: (item: string, field: string, variable: string) => `account ${item}.${field}: environment variable ${variable} is not set in the hub`,
	accountKeychainMissing: (item: string, field: string, keychain: string) => `account ${item}.${field}: keychain item "${keychain}" not found (security find-generic-password -s ${keychain})`,
	leaseMissing: (id: number) => `no lease ${id}`,
	shellTimeout: (seconds: number) => `[omp-home] timed out after ${seconds}s`,
	continuedWorktreeState: (task: string, dir: string, state: "ready" | "missing" | "removed") => `${task}'s worktree ${dir} is ${state}`,
	worktreeState: (dir: string, state: "ready" | "missing" | "removed") => `worktree ${dir} is ${state}`,
	invalidBranch: (branch: string) => `"${branch}" is not a valid branch name`,
	branchInUse: (branch: string, dir: string, task: string) => `branch ${branch} already has worktree ${dir} (task ${task}); dispatch with checkout {kind:"continue", task:"${task}"} instead`,
	sessionHasOpenTask: (session: string, task: string) => `${session} in this worktree still has open task ${task}; close it first`,
	worktreeBranchMismatch: (dir: string, actual: string | null, expected: string) => `${dir} is a worktree on ${actual ?? "detached HEAD"}, not ${expected}`,
};

const holderKinds = { worktree: "工作树", service: "服务", session: "会话" };
const worktreeStates = { ready: "就绪", missing: "缺失", removed: "已移除" };

export const envMessages = defineMessages(en, {
	worktreeMissing: id => `磁盘上找不到工作树 ${id}`,
	invalidRecipe: (file, errors) => `环境配方 ${file} 无效：${localizeFieldErrors(errors, "zh").map(e => `${e.path || "（根节点）"}：${e.message}`).join("；")}`,
	setupFailed: (code, command, output) => `环境准备命令失败（退出码 ${code}）：${command}\n${render(output, "zh")}`,
	environmentFailed: detail => `环境准备失败：${render(detail, "zh")}`,
	withLog: (detail, log) => `${render(detail, "zh")}\n日志：${log}`,
	databaseLeased: (name, holderKind, holderId) => `数据库 ${name} 已由${holderKinds[holderKind]} ${holderId} 租用`,
	databaseCloneFailed: (code, output) => `数据库克隆失败（退出码 ${code}）：${render(output, "zh")}`,
	startFailed: (code, output) => `启动失败（退出码 ${code}）：${render(output, "zh")}`,
	serviceStartFailed: (name, code, log) => `服务 ${name} 启动失败（退出码 ${code}）。日志：${log}`,
	checkTimeout: seconds => `${seconds} 秒后检查仍未通过`,
	serviceCheckTimeout: (name, seconds, log, tail) => `服务 ${name} 在 ${seconds} 秒后检查仍未通过。日志：${log}\n${tail}`,
	serviceMissing: (id, workspace) => `仓库 ${workspace} 的环境配方中没有服务 ${id}`,
	checkFailed: code => `检查失败（退出码 ${code}）`,
	stopFailed: (code, output) => `停止失败（退出码 ${code}）：${render(output, "zh").slice(-500)}`,
	noStopCommand: id => `环境配方未为服务 ${id} 定义停止命令`,
	teardownFailed: (code, command, log) => `环境清理命令失败（退出码 ${code}）：${command}。日志：${log}`,
	databaseDropFailed: (code, log) => `数据库删除失败（退出码 ${code}）。日志：${log}`,
	portsExhausted: (lo, hi) => `${lo}-${hi} 范围内没有空闲端口；扩大 settings.portRange 或清理已完成的任务`,
	noValidRecipe: workspace => `仓库 ${workspace} 没有有效的环境配方`,
	noAccountPool: (pool, known) => `没有账号池「${pool}」${known.length ? `；可用账号池：${known.join("、")}` : "；环境配方尚未定义账号池"}`,
	accountsLeased: (count, pool) => `「${pool}」中的 ${count} 个账号均已租出；等执行者本轮结束后再试`,
	accountEnvMissing: (item, field, variable) => `账号 ${item}.${field}：中枢未设置环境变量 ${variable}`,
	accountKeychainMissing: (item, field, keychain) => `账号 ${item}.${field}：找不到钥匙串项目「${keychain}」（security find-generic-password -s ${keychain}）`,
	leaseMissing: id => `没有租约 ${id}`,
	shellTimeout: seconds => `[omp-home] ${seconds} 秒后超时`,
	continuedWorktreeState: (task, dir, state) => `${task} 的工作树 ${dir} 状态为${worktreeStates[state]}`,
	worktreeState: (dir, state) => `工作树 ${dir} 状态为${worktreeStates[state]}`,
	invalidBranch: branch => `「${branch}」不是有效的分支名`,
	branchInUse: (branch, dir, task) => `分支 ${branch} 已有工作树 ${dir}（任务 ${task}）；改用 checkout {kind:"continue", task:"${task}"} 派发任务`,
	sessionHasOpenTask: (session, task) => `此工作树中的会话 ${session} 仍有未关闭的任务 ${task}；先关闭该任务`,
	worktreeBranchMismatch: (dir, actual, expected) => `${dir} 是${actual === null ? "处于分离 HEAD 状态" : `位于分支 ${actual}`}的工作树，并非位于分支 ${expected}`,
});
