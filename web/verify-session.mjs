import assert from "node:assert/strict";
import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";

// Run with a Puppeteer Chromium page against VITE_MOCK=1. The browser prelude can
// import this module in tab.run and call verifySession(page, outputDirectory).
export async function verifySession(page, outputDirectory) {
	await mkdir(outputDirectory, { recursive: true });
	const errors = [];
	page.on("pageerror", error => errors.push(String(error)));
	await page.reload({ waitUntil: "networkidle0" });
	await page.waitForSelector('.main-pane [data-tool="bash"] .tool-status.done');
	const main = '.main-pane';
	const screenshot = async name => { await page.screenshot({ path: join(outputDirectory, `${name}.png`), fullPage: false }); };
	await page.$eval(`${main} .transcript-scroll`, element => { element.scrollTop = 0; });
	assert.equal(await page.$eval(`${main} .thinking-block`, element => element.open), false);
	assert.equal(await page.$$eval(`${main} .tool-card[open]`, elements => elements.length), 0);
	await screenshot("01-collapsed-chat");
	await page.click(`${main} [data-tool="bash"] summary`);
	await page.waitForFunction(() => document.querySelector('.main-pane [data-tool="bash"] .tool-output:last-child')?.textContent.includes("3 tests passed"));
	await screenshot("02-expanded-tool");
	await page.click(`${main} [data-tool="bash"] summary`);
	await page.$eval(`${main} .request-card`, element => element.scrollIntoView({ block: "center" }));
	await page.click(`${main} .request-card .request-options button`);
	await page.waitForFunction(() => document.querySelector('.main-pane .request-card.answered .request-answer')?.textContent === "Approve");
	await screenshot("03-approval-answered");
	await page.click(`${main} input[type="radio"]`);
	await page.click(`${main} input[type="checkbox"]`);
	await page.click(`${main} .request-card:not(.answered) form > button`);
	await page.waitForFunction(() => document.querySelectorAll('.main-pane .request-card.answered').length === 2);
	await page.click(`${main} .session-activity button[aria-expanded]`);
	await page.waitForSelector(`${main} .nested-transcript code`);
	assert.match(await page.$eval(`${main} .nested-transcript`, element => element.textContent), /index\.update/);
	await screenshot("04-subagent-transcript");
	await page.type(`${main} .subagent-controls textarea`, "Check deleted paths too.");
	await page.click(`${main} .subagent-controls button[type="submit"], ${main} .subagent-controls button.primary`);
	await page.waitForFunction(() => document.querySelector('.main-pane .nested-transcript')?.textContent.includes("Check deleted paths too."));
	await page.click(`${main} .subagent-controls button.danger`);
	await page.waitForFunction(() => document.querySelector('.main-pane .subagent-row.selected')?.textContent.includes("aborted"));
	await page.click(`${main} [aria-label="Close subagents"]`);
	await page.$eval(`${main} .transcript-scroll`, element => { element.scrollTop = 0; });
	await page.click(`${main} .history-button`);
	await page.waitForSelector(`${main} [data-tool="edit"]`);
	await page.click(`${main} [data-tool="edit"] summary`);
	assert.match(await page.$eval(`${main} .diff-new`, element => element.textContent), /index\.update/);
	await page.click(`${main} .request-card button.primary`);
	await page.waitForFunction(() => document.querySelector('.main-pane .request-card.answered .request-answer')?.textContent === "Yes");
	await page.type(`${main} input[aria-label="Name the preview environment"]`, "staging-preview");
	await page.click(`${main} input[aria-label="Name the preview environment"] + button`);
	await page.waitForFunction(() => Array.from(document.querySelectorAll('.main-pane .request-answer')).some(element => element.textContent === "staging-preview"));
	await page.click(`${main} textarea[aria-label="Review the rollout note"] + button`);
	await page.waitForFunction(() => document.querySelectorAll('.main-pane .request-card.answered').length === 3);
	await screenshot("05-history-and-diff");
	await page.click(`${main} .jump-latest`);
	const composer = `${main} textarea[aria-label="M-1 message"]`;
	await page.type(composer, "/mdl");
	await page.waitForSelector(`${main} .command-menu`);
	assert.match(await page.$eval(`${main} .command-menu`, element => element.textContent), /\/model/);
	await page.keyboard.press("Tab");
	assert.equal(await page.$eval(composer, element => element.value), "/model ");
	await page.$eval(composer, element => { element.focus(); element.select(); });
	await page.keyboard.press("Backspace");
	assert.equal(await page.$eval(composer, element => element.value), "");
	const initialUserMessages = await page.$$eval('.main-pane .user-bubble', elements => elements.length);
	await page.evaluate(() => {
		window.__sessionVerification = { composition: [] };
		const input = document.querySelector('textarea[aria-label="M-1 message"]');
		for (const type of ["compositionstart", "compositionend", "keydown", "input"]) input.addEventListener(type, event => window.__sessionVerification.composition.push({ type, key: event.key, isComposing: event.isComposing, data: event.data }));
	});
	const cdp = await page.createCDPSession();
	await cdp.send("Input.imeSetComposition", { text: "中文输入", selectionStart: 4, selectionEnd: 4 });
	await cdp.send("Input.dispatchKeyEvent", { type: "keyDown", key: "Enter", code: "Enter", windowsVirtualKeyCode: 13 });
	await cdp.send("Input.dispatchKeyEvent", { type: "keyUp", key: "Enter", code: "Enter", windowsVirtualKeyCode: 13 });
	assert.equal(await page.$$eval('.main-pane .user-bubble', elements => elements.length), initialUserMessages);
	await cdp.send("Input.insertText", { text: "中文输入安全" });
	assert.equal(await page.$eval(composer, element => element.value), "中文输入安全");
	assert.equal(await page.$$eval('.main-pane .user-bubble', elements => elements.length), initialUserMessages);
	await screenshot("06-ime-composed-unsent");
	await page.click(`${main} .composer-actions button.primary`);
	const ime = await page.evaluate(() => window.__sessionVerification);
	assert(ime.composition.some(event => event.type === "keydown" && event.key === "Enter" && event.isComposing));
	await page.waitForFunction(() => Array.from(document.querySelectorAll('.main-pane .user-bubble')).some(element => element.textContent === "中文输入安全"));
	assert.equal(await page.$$eval('.main-pane .user-bubble', elements => elements.filter(element => element.textContent === "中文输入安全").length), 1);
	ime.sentExactlyOnce = true;
	ime.prematureMessages = 0;
	await screenshot("07-ime-sent-once");
	await page.click('.workspace-pane .card .btn.primary');
	await page.waitForSelector('.workspace-pane textarea[aria-label="W-12 message"]');
	await page.waitForSelector('.workspace-pane [data-tool="bash"] .tool-status.done');
	await page.$eval('.workspace-pane .transcript-scroll', element => { element.scrollTop = 0; });
	await screenshot("08-worker-session");
	await page.focus(composer); await page.keyboard.press("Escape");
	await page.waitForFunction(() => !document.querySelector('.main-pane .activity-state'));
	assert.deepEqual(errors, []);
	const result = { passed: true, screenshots: 8, checks: ["collapsed thinking/tools", "expanded tool output", "select answered", "ask multi-question answered", "nested transcript", "subagent steer/cancel", "history paging", "edit diff", "confirm/input/editor answered", "fuzzy commands", "CDP Chinese IME does not send before explicit Send", "worker session", "Escape abort"], ime, errors };
	await writeFile(join(outputDirectory, "result.json"), JSON.stringify(result, null, 2));
	await cdp.detach();
	return result;
}
